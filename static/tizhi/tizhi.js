  // —— 判定（标准第 5 章） ——
  // 平和质：转化分 ≥ 60 且其余八型均 < 30 →「是」；≥ 60 且其余八型均 < 40 →「基本是」；否则「否」
  // 偏颇体质：≥ 40 →「是」；30～39 →「倾向是」（取 30 ≤ 分 < 40）；< 30 →「否」
  const LINE = { PING: 60, PING_YES: 30, PING_JI: 40, YES: 40, QING: 30 };
  function levelPian(s) { return s >= LINE.YES ? '是' : s >= LINE.QING ? '倾向是' : '否'; }
  function levelPing(sc) {
    const p = sc.pinghe, mx = Math.max(...PIAN.map(k => sc[k]));
    if (p >= LINE.PING && mx < LINE.PING_YES) return '是';
    if (p >= LINE.PING && mx < LINE.PING_JI) return '基本是';
    return '否';
  }
  const byScore = sc => (a, b) => (sc[b] - sc[a]) || (ORDER.indexOf(a) - ORDER.indexOf(b));
  const EPS = 1e-9;
  // 本页约定：几型都「是」时，分最高者为主体质（同分并列），其余为兼夹；「倾向是」列为倾向
  function verdict(sc) {
    if (!sc || ORDER.some(k => typeof sc[k] !== 'number' || isNaN(sc[k]))) return null;
    const levels = { pinghe: levelPing(sc) };
    PIAN.forEach(k => { levels[k] = levelPian(sc[k]); });
    const yes = PIAN.filter(k => levels[k] === '是').sort(byScore(sc));
    const qing = PIAN.filter(k => levels[k] === '倾向是').sort(byScore(sc));
    const top = ks => ks.filter(k => sc[k] > sc[ks[0]] - EPS);
    let kind, main = [], jian = [], qx = qing;
    if (levels.pinghe === '是') { kind = 'pinghe'; main = ['pinghe']; }
    else if (levels.pinghe === '基本是') { kind = 'pinghe-ji'; main = ['pinghe']; }
    else if (yes.length) { kind = 'pian'; main = top(yes); jian = yes.filter(k => main.indexOf(k) < 0); }
    else if (qing.length) { kind = 'qing'; main = top(qing); qx = qing.filter(k => main.indexOf(k) < 0); }
    else kind = 'none';
    return { scores: Object.assign({}, sc), levels, ping: levels.pinghe, kind, main, jian, qing: qx };
  }
  // 某型在这次结果里的身份
  function roleOf(v, k) {
    if (v.main.indexOf(k) >= 0) return v.kind === 'qing' ? '倾向' : '主体质';
    if (v.jian.indexOf(k) >= 0) return '兼夹';
    if (v.qing.indexOf(k) >= 0) return '倾向';
    return '';
  }

  // —— 一句白话结论；wrap 用来给主体质名字上色（页面传入，node 里原样） ——
  function lines(v, opt) {
    const w = (opt && opt.wrap) || (s => s);
    const R = k => Math.round(v.scores[k]);
    const names = ks => ks.map(k => TYPE[k].name);
    const list = ks => { const n = names(ks); return n.length > 3 ? n.slice(0, 3).join('、') + `等 ${n.length} 种` : n.join('、'); };
    const ping = R('pinghe');
    let key, sub;
    if (v.kind === 'pinghe') {
      key = `你是${w('平和质')}`;
      sub = `平和质 ${ping} 分；八种偏颇体质都不到 30 分。`;
    } else if (v.kind === 'pinghe-ji') {
      key = `基本是${w('平和质')}`;
      sub = `平和质 ${ping} 分；另有${list(v.qing)}倾向（30～39 分），可留意下面的建议。`;
    } else if (v.kind === 'pian') {
      key = `主体质：${w(list(v.main))}`;
      const bits = [];
      if (v.main.length > 1) bits.push(`${v.main.length} 型同分（${R(v.main[0])} 分）`);
      if (v.jian.length) bits.push(`兼夹${list(v.jian)}`);
      if (v.qing.length) bits.push(`有${list(v.qing)}倾向`);
      sub = (bits.length ? bits.join('；') : '其余各型都没到判定线') + '。';
      if (v.scores.pinghe >= LINE.PING) sub += `平和质虽有 ${ping} 分，但有偏颇到了 40 分，按标准不判平和。`;
    } else if (v.kind === 'qing') {
      key = `有${w(list(v.main))}倾向`;
      sub = `没有哪一型到 40 分（「是」的线）${v.qing.length ? `；另有${list(v.qing)}倾向` : ''}；平和质 ${ping} 分，未到 60，不判平和。`;
    } else {
      key = w('未见明显偏颇');
      sub = `八种偏颇都不到 30 分，但平和质 ${ping} 分、未到 60，按标准也不算平和质。可隔段时间再测，或请中医面诊。`;
    }
    return { key, sub };
  }

  // —— 存档：61 条压成一串数字（Q 的次序，0 = 未答或不适用） ——
  function pack(ans) { return Q.map(q => (ans[q.id] >= 1 && ans[q.id] <= 5) ? String(ans[q.id]) : '0').join(''); }
  function unpack(s) {
    const ans = {};
    if (typeof s !== 'string') return ans;
    Q.forEach((q, i) => { const d = +s[i]; if (d >= 1 && d <= 5) ans[q.id] = d; });
    return ans;
  }

  // —— 复制、问 AI 用的一段文字 ——
  const lvTxt = (v, k) => v.levels[k];
  function scoreLine(v) { return ORDER.map(k => `${TYPE[k].short} ${Math.round(v.scores[k])}（${lvTxt(v, k)}）`).join('｜'); }
  // 列出答「经常」「总是」的条目（平和质两条正向题另列）
  function salient(ans, sex) {
    const qs = questions(sex), hi = [], fwd = [];
    qs.forEach(q => {
      const a = ans[q.id];
      if (!a) return;
      const pingFwd = q.id === 'A1' || q.id === 'A6';
      if (pingFwd) fwd.push(`${q.t}——${OPTS[a - 1].n}`);
      else if (a >= 4) hi.push(`${q.t}——${OPTS[a - 1].n}`);
    });
    return { hi, fwd };
  }
  function summary(o) {
    const v = o.v, L = lines(v), out = [];
    out.push(`中医体质辨识 · ${o.date || ''}${o.sex ? ' · ' + (o.sex === 'f' ? '女' : '男') : ''}（按《中医体质分类与判定》ZYYXH/T157-2009 的 60 条自评，近一年的感受）`);
    out.push(`结论：${L.key}。${L.sub}`);
    out.push(`九型转化分：${scoreLine(v)}`);
    if (o.ans) {
      const s = salient(o.ans, o.sex);
      out.push(s.hi.length ? `答「经常」「总是」的条目（${s.hi.length} 条）：${s.hi.join('；')}` : '没有答「经常」「总是」的条目。');
      if (s.fwd.length) out.push(`平和质的两条正向题：${s.fwd.join('；')}`);
    }
    if (o.prev) out.push(`上一次（${o.prev.date}）：${lines(o.prev.v).key}；${scoreLine(o.prev.v)}`);
    return out.join('\n');
  }

